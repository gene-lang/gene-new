proc builtinNativeEffectKind*(name: string): NativeEffectKind =
  # Binary search keeps construction inexpensive and rejects unknown additions.
  var low = 0
  var high = NativeEffectRules.high
  while low <= high:
    let mid = low + (high - low) div 2
    let order = cmp(name, NativeEffectRules[mid].name)
    if order == 0: return NativeEffectRules[mid].kind
    if order < 0: high = mid - 1
    else: low = mid + 1
  nekUnclassified
