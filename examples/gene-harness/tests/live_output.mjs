import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
const out=await import(pathToFileURL(process.argv[2]).href);
const chunk=(id,text,round='r',turn=1n,extra={})=>({id,text,round_id:round,turn,...extra});
const key=out.turn_output_key('s','r',1n);
const store=out.create_output();
out.output_epoch(store,'one');
assert.equal(out.receive_output(store,'s',chunk('2','second ')),true);
assert.equal(out.receive_output(store,'s',chunk('1','first')),true);
assert.equal(out.receive_output(store,'s',chunk('2','duplicate')),false);
assert.equal(out.output_entry(store,key).text,'second first');
out.receive_output(store,'other',chunk('3','private'));
out.receive_output(store,'s',chunk('4','different','other-round'));
out.receive_output(store,'s',chunk('5','<script>alert(1)</script>','r',1n,{late:true}));
assert.match(out.output_text(out.output_entry(store,key)),/Late output/);
assert.match(out.output_text(out.output_entry(store,key)),/<script>/);
assert.equal(out.receive_output(store,'s',chunk('unowned','not a turn','',0n)),false);
assert.equal(out.receive_output(store,'s',chunk('oversized-owner','ignored','r'.repeat(257))),false);
const historical=out.historical_records([{phase:'console',text:'old'}, {phase:'code',text:'code'}]);
assert.deepEqual(historical.map(x=>x.text),['code']);
assert.equal(out.create_output().entries.length,0,'reload creates an empty page store');
out.interrupt_output(store,'s');
assert.match(out.output_text(out.output_entry(store,key)),/interrupted/);
assert.doesNotMatch(out.output_text(out.output_entry(store,out.turn_output_key('other','r',1n))),/interrupted/);
out.receive_output(store,'s',chunk('resumed','later delta'));
out.observe_output(store,'s','turn',{phase:'turn/end',round_id:'r',turn:1n});
assert.match(out.output_text(out.output_entry(store,key)),/interrupted/,'a new delta and completion cannot repair a gap');
out.receive_output(store,'s',chunk('finished','complete','finished-round'));
out.observe_output(store,'s','snapshot',{records:[{phase:'turn/end',round_id:'finished-round',turn:1n}]});
out.interrupt_output(store,'s');
assert.doesNotMatch(out.output_text(out.output_entry(store,out.turn_output_key('s','finished-round',1n))),/interrupted/,'completed output must not gain a warning on a later disconnect');
out.receive_output(store,'s',chunk('command','a','',0n,{command_id:'c',cumulative:true}));
out.interrupt_output(store,'s');
out.receive_output(store,'s',chunk('command','abc','',0n,{command_id:'c',cumulative:true}));
assert.equal(out.output_entry(store,out.command_output_key('s','c')).text,'abc');
assert.doesNotMatch(out.output_text(out.output_entry(store,out.command_output_key('s','c'))),/interrupted/);
out.interrupt_output(store,'s');
assert.equal(out.receive_output(store,'s',chunk('command','abc','',0n,{command_id:'c',cumulative:true})),true,'identical cumulative content also repairs the warning');
assert.equal(out.receive_output(store,'s',chunk('command','abc','',0n,{command_id:'c',cumulative:true})),false);
out.clear_session_output(store,'s');
assert.equal(out.output_entry(store,key),null);
assert.ok(store.entries.every(x=>x.session==='other'));
out.output_epoch(store,'two');
assert.equal(store.entries.length,0);
assert.equal(out.output_epoch(store,'one'),false,'retired socket epochs cannot resurrect output');

const noisy=out.create_output();
out.receive_output(noisy,'s',chunk('unicode','雪😀'.repeat(100000)));
const unicode=out.output_entry(noisy,key);
assert.ok(unicode.bytes<=262144n);
assert.ok(!unicode.text.includes('�'));
assert.ok(unicode.truncated);
assert.match(out.output_text(unicode),/truncated/);
assert.equal(out.receive_output(noisy,'s',chunk('after','ignored')),false);
const commandCap=out.create_output();
out.receive_output(commandCap,'s',chunk('cmd','x'.repeat(300000),'',0n,{command_id:'large',cumulative:true}));
assert.equal(out.receive_output(commandCap,'s',chunk('cmd','x'.repeat(400000),'',0n,{command_id:'large',cumulative:true})),false);
const many=out.create_output();
for(let i=0;i<8193;i++) out.receive_output(many,'s',chunk('id'+i,'x'));
assert.equal(out.output_entry(many,key).chunks,8192n);
assert.ok(out.output_entry(many,key).truncated);
const page=out.create_output();
for(let i=0;i<24;i++) out.receive_output(page,'s',chunk('large'+i,'x'.repeat(250000),'r',BigInt(i+1)));
assert.ok(page.bytes<=4194304n);
assert.ok(page.chunks<=32768n);
assert.ok(page.entries.some(x=>x.evicted));
const pending=out.create_output();
for(let i=0;i<1100;i++) out.receive_output(pending,'s',chunk('orphan'+i,'x','r',BigInt(i+1)));
assert.ok(pending.entries.length<=1024,'pending owners and eviction markers are bounded');
console.log('Live output: ownership, deduplication, cumulative updates, reload/epoch/close, UTF-8 and byte/chunk/owner bounds passed.');
