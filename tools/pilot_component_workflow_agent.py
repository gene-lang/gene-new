"""Run the excluded experiment-4 version-3 component-wise difficulty pilot.

Each task starts a fresh qualified-model conversation. The model identifies one
ordered workflow component at a time and proposes exactly three catalog
operations for it. The public checker compares that candidate against only the
component's three already-public demonstrations, so every checker response is a
deterministic function of public data and the model's own arguments. The single
hidden comparison in an episode is the terminal submission. Pilot seeds never
enter treatment.
"""

